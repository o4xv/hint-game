const rowsByPack: Record<string, CardRow[]> = {
  core: coreRows,
  "daily-life": dailyRows,
  entertainment: entertainmentRows,
};

export const cards = PACK_DEFINITIONS.flatMap((pack) =>
  (rowsByPack[pack.id] ?? []).map(([id, left, right, anchors]) =>
    card(pack.id, id, left, right, anchors),
  ),
);
export const publicCards = cards.map(({ id, packId, left, right }) => ({
  id,
  packId,
  left,
  right,
}));
export const publicPacks = PACK_DEFINITIONS.map((pack) => ({
  ...pack,
  cardCount: (rowsByPack[pack.id] ?? []).length,
}));

export function getCardsForPacks(packIds: string[]) {
  const selected = new Set(packIds);
  return cards.filter((candidate) => selected.has(candidate.packId));
}

export function validatePackIds(packIds: unknown) {
  if (!Array.isArray(packIds) || packIds.length === 0) return null;
  const allowed = new Set(PACK_DEFINITIONS.map((pack) => pack.id));
  const unique = [...new Set(packIds.map(String))];
  return unique.every((id) => allowed.has(id)) ? unique : null;
}

export const DEFAULT_PACK_IDS = PACK_DEFINITIONS.filter((pack) => pack.defaultEnabled).map(
  (pack) => pack.id,
);
export default cards;
