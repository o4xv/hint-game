function suitabilityFor(cardId: string) {
  const profile = EDGE_LEANING_CARD_IDS.has(cardId)
    ? SUITABILITY_PROFILES.edgeLeaning
    : INNER_STRONG_CARD_IDS.has(cardId)
      ? SUITABILITY_PROFILES.innerStrong
      : SUITABILITY_PROFILES.balanced;
  return [...profile];
}

function card(packId: string, id: string, left: string, right: string, anchors: string[]) {
  if (
    !left ||
    !right ||
    !Array.isArray(anchors) ||
    anchors.length !== 5 ||
    anchors.some((value) => !value.trim())
  ) {
    throw new Error(`Invalid five-anchor card: ${id}`);
  }
  return { id, packId, left, right, editorial: { anchors, suitability: suitabilityFor(id) } };
}

